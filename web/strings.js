export function localeCode(value) {
  const v = String(value ?? '').trim().toLowerCase().replace(/_/g, '-');
  if (v === 'de' || v.startsWith('de-')) return 'de';
  if (v === 'en' || v.startsWith('en-')) return 'en';
  return '';
}

// Query wins, then the saved choice, then the browser language, then English.
export function resolveLocale({ query, stored, nav } = {}) {
  return localeCode(query) || localeCode(stored) || (String(nav || '').toLowerCase().startsWith('de') ? 'de' : 'en');
}

export function translate(locale, key, vars) {
  const lang = UI[locale] ? locale : 'en';
  let text = UI[lang][key] ?? UI.en[key];
  if (text == null) return '';
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function textOrServer(locale, value, vars) {
  if (!value) return '';
  const key = `detail.${value}`;
  if (UI.en[key] == null) return String(value);
  return translate(locale, key, vars);
}

export function captionLine(locale, state, states) {
  const lang = CAPTIONS[locale] ? locale : 'en';
  const base = CAPTIONS[lang][state] || CAPTIONS.en[state] || null;
  const over = states?.[state]?.[lang === 'de' ? 'de' : 'en'];
  if (over) return { text: over, dots: !!base?.dots };
  return base;
}

export function detailLine(locale, state) {
  const lang = DETAILS[locale] ? locale : 'en';
  return DETAILS[lang][state] || DETAILS.en[state] || '';
}

export function stateLabel(locale, state) {
  return translate(locale, `state.${state}`);
}
